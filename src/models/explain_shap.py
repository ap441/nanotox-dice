#!/usr/bin/env python3
"""
Diagnostic SHAP feature explanation pipeline for Safe-by-Design Nanotoxicology.

Computes TreeExplainer SHAP values on holdout test sets for:
  - models/cytotox_best_model.joblib (Mammalian Biocompatibility)
  - models/seltox_best_model.joblib  (Bacterial Antimicrobial Potency)

Outputs:
  - results/figures/shap_cytotox_summary.png (300 dpi beeswarm plot)
  - results/figures/shap_seltox_summary.png  (300 dpi beeswarm plot)
  - results/tables/shap_top_features.csv     (Top 15 mean absolute SHAP values)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

import joblib
import matplotlib
matplotlib.use("Agg")  # Non-interactive backend
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import shap


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compute and export diagnostic SHAP explanations for best baseline models."
    )
    parser.add_argument(
        "--models-dir",
        type=Path,
        default=Path("models"),
        help="Path to directory containing saved joblib models (default: models).",
    )
    parser.add_argument(
        "--processed-dir",
        type=Path,
        default=Path("data/processed"),
        help="Path to directory containing processed test sets (default: data/processed).",
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=Path("results/figures"),
        help="Directory to save SHAP beeswarm figures (default: results/figures).",
    )
    parser.add_argument(
        "--tables-dir",
        type=Path,
        default=Path("results/tables"),
        help="Directory to save tabular SHAP feature importance (default: results/tables).",
    )
    return parser.parse_args()


def clean_feature_names(raw_names: List[str]) -> List[str]:
    """Clean feature names generated by ColumnTransformer OneHotEncoder."""
    cleaned: List[str] = []
    for name in raw_names:
        clean = name.replace("num__", "").replace("cat__", "")
        cleaned.append(clean)
    return cleaned


def explain_model_task(
    task_name: str,
    task_title: str,
    target_name: str,
    model_path: Path,
    test_path: Path,
    figures_dir: Path,
) -> Tuple[pd.DataFrame, Path]:
    """Compute SHAP values, plot beeswarm, and return top feature dataframe."""
    print(f"\n{'=' * 70}")
    print(f"SHAP Diagnostic Analysis: {task_title}")
    print(f"Model Artifact: {model_path}")
    print(f"Holdout Test Set: {test_path}")
    print(f"{'=' * 70}")

    if not model_path.exists():
        raise FileNotFoundError(f"Model artifact missing at {model_path}")
    if not test_path.exists():
        raise FileNotFoundError(f"Holdout test data missing at {test_path}")

    pipeline = joblib.load(model_path)
    test_df = pd.read_csv(test_path)

    preprocessor = pipeline.named_steps["preprocessor"]
    classifier = pipeline.named_steps["classifier"]

    # Extract feature matrix matching pipeline training schema
    feature_cols = list(pipeline.feature_names_in_)
    X_test = test_df[feature_cols]

    print(f"[TRANSFORM] Preprocessing {len(X_test):,} holdout test instances...")
    X_trans = preprocessor.transform(X_test)
    raw_feature_names = list(preprocessor.get_feature_names_out())
    feature_names = clean_feature_names(raw_feature_names)
    print(f"[TRANSFORM] Transformed feature space: {X_trans.shape[1]} columns.")

    print(f"[SHAP] Computing TreeExplainer SHAP values (model: {type(classifier).__name__})...")
    explainer = shap.TreeExplainer(classifier)
    shap_explanation = explainer(X_trans)

    # For binary classification, select positive class (index 1)
    if len(shap_explanation.shape) == 3:
        exp_pos = shap_explanation[:, :, 1]
    else:
        exp_pos = shap_explanation

    exp_pos.feature_names = feature_names

    # 1. Generate High-Resolution Beeswarm Plot
    figures_dir.mkdir(parents=True, exist_ok=True)
    out_fig_path = figures_dir / f"shap_{task_name}_summary.png"

    print(f"[PLOT] Generating high-resolution SHAP summary plot...")
    plt.figure(figsize=(11, 7), dpi=300)
    shap.plots.beeswarm(exp_pos, max_display=15, show=False)
    plt.title(
        f"SHAP Feature Attribution (Top 15 Levers): {task_title}\nTarget: P({target_name}=1)",
        fontsize=13,
        pad=15,
        fontweight="bold",
    )
    plt.xlabel("SHAP Value (Impact on Model Log-Odds Output)", fontsize=11)
    plt.tight_layout()
    plt.savefig(out_fig_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"[SAVED] SHAP beeswarm figure saved to {out_fig_path.resolve()}")

    # 2. Extract Mean Absolute SHAP Importance
    shap_vals_matrix = exp_pos.values
    mean_abs_shap = np.mean(np.abs(shap_vals_matrix), axis=0)
    total_abs_shap = np.sum(mean_abs_shap)

    sorted_indices = np.argsort(mean_abs_shap)[::-1][:15]

    top_records: List[Dict[str, Any]] = []
    for rank, idx in enumerate(sorted_indices, 1):
        feat = feature_names[idx]
        val = float(mean_abs_shap[idx])
        rel_pct = float((val / max(1e-9, total_abs_shap)) * 100)
        top_records.append(
            {
                "task": task_name,
                "rank": rank,
                "feature": feat,
                "mean_abs_shap": round(val, 5),
                "relative_importance_pct": round(rel_pct, 2),
            }
        )

    top_df = pd.DataFrame(top_records)

    print(f"\nTop 10 Influential Features ({task_name}):")
    for row in top_records[:10]:
        print(f"  #{row['rank']:2d} | {row['feature']:<35s} | Mean |SHAP|: {row['mean_abs_shap']:.5f} ({row['relative_importance_pct']:.1f}%)")

    return top_df, out_fig_path


def main() -> int:
    args = parse_args()

    print("=" * 75)
    print("Safe-by-Design Nanotox SHAP Model Interpretability Pipeline")
    print(f"Models Directory: {args.models_dir.resolve()}")
    print(f"Figures Directory: {args.figures_dir.resolve()}")
    print(f"Tables Directory: {args.tables_dir.resolve()}")
    print("=" * 75)

    tasks_config = [
        {
            "task_name": "cytotox",
            "task_title": "Mammalian Biocompatibility (Cytotox)",
            "target_name": "is_biocompatible",
            "model_path": args.models_dir / "cytotox_best_model.joblib",
            "test_path": args.processed_dir / "cytotox_test.csv",
        },
        {
            "task_name": "seltox",
            "task_title": "Antimicrobial Efficacy (SelTox)",
            "target_name": "is_antibacterial",
            "model_path": args.models_dir / "seltox_best_model.joblib",
            "test_path": args.processed_dir / "seltox_test.csv",
        },
    ]

    all_top_dfs: List[pd.DataFrame] = []

    for task_info in tasks_config:
        try:
            top_df, _ = explain_model_task(
                task_name=task_info["task_name"],
                task_title=task_info["task_title"],
                target_name=task_info["target_name"],
                model_path=task_info["model_path"],
                test_path=task_info["test_path"],
                figures_dir=args.figures_dir,
            )
            all_top_dfs.append(top_df)
        except Exception as exc:
            print(f"[ERROR] Failed explaining {task_info['task_name']}: {exc}", file=sys.stderr)
            return 1

    # Export combined top features table
    args.tables_dir.mkdir(parents=True, exist_ok=True)
    out_table_path = args.tables_dir / "shap_top_features.csv"
    combined_df = pd.concat(all_top_dfs, ignore_index=True)
    combined_df.to_csv(out_table_path, index=False)
    print(f"\n[SAVED] Top SHAP features exported to {out_table_path.resolve()}")

    print("\n[SUCCESS] SHAP explanation pipeline completed successfully.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
